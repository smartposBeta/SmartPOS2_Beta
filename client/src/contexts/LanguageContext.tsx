const getTagalogTranslation = (text: string): string => {
  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? '';
  const phrase = text.slice(leadingWhitespace.length, text.length - trailingWhitespace.length);
  if (!phrase) return text;

  const normalizedPhrase = phrase.replace(/\s+/g, ' ').toLocaleLowerCase();
  const translatedPhrase = tagalogPhrases[normalizedPhrase];
  if (translatedPhrase) return `${leadingWhitespace}${translatedPhrase}${trailingWhitespace}`;

  const englishTranslations = translations.en as Record<string, string>;
  const translationKey = Object.keys(englishTranslations).find(
    (key) => englishTranslations[key].toLocaleLowerCase() === normalizedPhrase,
  );
  const existingTranslation = translationKey
    ? (translations.tl as Record<string, string>)[translationKey]
    : undefined;
  return existingTranslation
    ? `${leadingWhitespace}${existingTranslation}${trailingWhitespace}`
    : text;
};

export type TranslationKey = keyof typeof translations.en | (string & {});

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, fallback?: string) => string;
  translateText: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

const getInitialLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return savedLanguage === 'tl' ? 'tl' : 'en';
};

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language === 'tl' ? 'tl' : 'en';
  }, [language]);

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
  };

  const value: LanguageContextValue = {
    language,
    setLanguage,
    t: (key: string, fallback?: string) => {
      const dict = translations[language] as Record<string, string>;
      const enDict = translations.en as Record<string, string>;
      if (dict && dict[key]) return dict[key];
      if (enDict && enDict[key]) return enDict[key];
      return fallback || key;
    },
    translateText: (text: string) => language === 'tl' ? getTagalogTranslation(text) : text,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

const localizeNode = (node: ReactNode, translateText: (text: string) => string): ReactNode => {
  if (typeof node === 'string') return translateText(node);
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, translateText));
  if (!isValidElement(node)) return node;

  const props = node.props as Record<string, unknown>;
  const localizedProps: Record<string, unknown> = {};
  if ('children' in props) {
    localizedProps.children = localizeNode(props.children as ReactNode, translateText);
  }

  for (const attribute of ['placeholder', 'title', 'subtitle', 'label', 'description', 'aria-label', 'aria-description', 'alt']) {
    const value = props[attribute];
    if (typeof value === 'string') localizedProps[attribute] = translateText(value);
  }

  return cloneElement(node, localizedProps);
};

export const LocalizedContent: React.FC<{ children: ReactNode }> = ({ children }) => {
  const { translateText } = useLanguage();
  return <>{localizeNode(children, translateText)}</>;
};

export const useLanguage = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};